#!/usr/bin/env bash
# First-time setup: generate secrets and write .env
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$SCRIPT_DIR/.."
ENV_FILE="$ROOT/.env"

if [[ -f "$ENV_FILE" ]]; then
  echo "[warn] .env already exists. Delete it first to regenerate."
  exit 1
fi

echo "[setup] Generating secrets..."

gen64() { openssl rand -hex 64; }
gen32() { openssl rand -hex 32; }
gen16() { openssl rand -hex 16; }
genpass() { openssl rand -base64 18 | tr -d '/+=' | head -c 20; }

cat > "$ENV_FILE" <<EOF
# =============================================
# ClientFacing Stack — Generated by setup.sh
# $(date)
# =============================================

# Shared PostgreSQL
POSTGRES_USER=cfadmin
POSTGRES_PASSWORD=$(genpass)

# MariaDB (BookStack)
MARIADB_ROOT_PASSWORD=$(genpass)
MARIADB_PASSWORD=$(genpass)

# MinIO (shared storage)
MINIO_ROOT_USER=cfminio
MINIO_ROOT_PASSWORD=$(genpass)minio

# Chatwoot
CHATWOOT_SECRET_KEY_BASE=$(gen64)

# Documenso
DOCUMENSO_NEXTAUTH_SECRET=$(gen32)
DOCUMENSO_ENCRYPTION_KEY=$(gen16)
DOCUMENSO_ENCRYPTION_KEY_SECONDARY=$(gen16)

# n8n
N8N_BASIC_AUTH_USER=admin
N8N_BASIC_AUTH_PASSWORD=$(genpass)

# Plane
PLANE_SECRET_KEY=$(gen32)
PLANE_ADMIN_PASSWORD=$(genpass)
EOF

echo "[setup] .env written to $ENV_FILE"
echo ""
echo "Next: create MinIO buckets (after first 'make up'):"
echo "  make buckets"
echo ""
echo "Then run database migrations:"
echo "  make migrate"
